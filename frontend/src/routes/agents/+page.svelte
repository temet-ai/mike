						onclick={() => (searchQuery = '')}><X class="size-4" aria-hidden="true" /></Button
					>
				{/if}
				{#if !loading && agents.length > 0}
					<div class="ag-filters" role="group" aria-label="Filter by source">
						{#each SOURCE_FILTERS as filter (filter.value)}
							<button
								type="button"
								class="ag-filter-chip"
								class:ag-filter-chip--active={sourceFilter === filter.value}
								aria-pressed={sourceFilter === filter.value}
								data-slot="agents-source-filter-chip"
								data-source={filter.value}
