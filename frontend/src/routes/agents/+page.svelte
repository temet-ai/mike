		{:else if !loading && agents.length === 0}
			<div data-slot="agents-empty">
				<EmptyStateOnboarding
					headline="No agents registered yet"
					body="Agents appear here as named Claude sub-agents are observed in captured request traffic, or when you register one against a composition."
					command={null}
					confirmation="Register a composition with an agent name from the prompts page to see it appear here."
					onOpenHelp={openHelp}
				>
					{#snippet actions()}
						<a
							class="inline-flex items-center gap-1.5 rounded border border-[var(--border-default)] bg-[var(--surface-card)] px-3 py-1.5 text-xs text-[var(--text-2)] no-underline transition-colors hover:border-[var(--interactive-active-border)] hover:text-[var(--text-strong)] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[var(--interactive-focus-ring)]"
							href={resolve('/prompts')}
							data-slot="agents-empty-prompts-link"
