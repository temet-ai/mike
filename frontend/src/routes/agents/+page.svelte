<section class="flex h-full flex-col overflow-hidden" data-slot="agents-page" use:revealSections>
	<header
		class="flex flex-wrap items-start justify-between gap-4 border-b border-[var(--border-default)] px-6 py-5"
		data-reveal
	>
		<PageIntro
			title="Agents"
			level="h1"
			description="Every agent identity observed — dispatched sub-agent runs, captured prompt versions, and instances. Click into one to see its full evidence trail."
