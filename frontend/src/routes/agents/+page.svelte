					onClearFilters={() => {
						searchQuery = '';
						sourceFilter = 'all';
					}}
				/>
			{:else}
				<div class="ag-rows" data-reveal data-slot="agents-rows">
					{#each visibleAgents as a (a.id)}
						<a
							href={resolve(`/agents/${a.id}`)}
							class="ag-row-wrap"
							data-slot="agent-row"
							data-agent-id={a.id}
							data-agent-name={a.name}
						>
							<div class="ag-row-main">
								<span class="ag-row-identity" data-slot="agent-row-identity">
									<span class="ag-row-name" data-slot="agent-row-name"
										><Bot class="size-4" aria-hidden="true" />{a.name}</span
									>
									<Tooltip text={SOURCE_TOOLTIP[a.source]} slug={SOURCE_SLUG[a.source]}>
										{#snippet child({ props })}
											<span
												{...props}
												class="badge-nx {SOURCE_BADGE[a.source]}"
												data-slot="agent-row-source"
											>
												{a.source === 'file_backed' ? 'file-backed' : a.source}
											</span>
										{/snippet}
									</Tooltip>
									{#if a.aliases && a.aliases.length > 0}
										<span class="ag-row-aliases" data-slot="agent-row-aliases">
											{#each a.aliases as alias (alias.alias)}
												<span
													class="ag-alias-chip"
													title={alias.kind === 'persona' ? 'Persona alias' : 'Name-variant alias'}
												>
													{alias.alias}
												</span>
											{/each}
										</span>
									{/if}
								</span>
								<span class="ag-row-fill"></span>
								<span class="ag-row-meta" data-slot="agent-row-dispatch-count">
									{a.dispatch_count} dispatch{a.dispatch_count === 1 ? '' : 'es'}
								</span>
								<span class="ag-row-meta" data-slot="agent-row-version-count">
									{a.prompt_version_count} prompt version{a.prompt_version_count === 1 ? '' : 's'}
								</span>
								<span
									class="ag-row-meta ag-row-meta--muted"
									data-slot="agent-row-composition-count"
								>
									{a.composition_count} composition{a.composition_count === 1 ? '' : 's'}
								</span>
								<span class="ag-row-timestamp" data-slot="agent-row-last-dispatched">
									{#if a.last_dispatched_at !== null}
										last dispatched <b>{formatRelative(a.last_dispatched_at)}</b>
									{:else}
										never dispatched
									{/if}
								</span>
							</div>

							{#if a.definition_path !== null && a.definition_path.length > 0}
								<p
									class="ag-row-path"
									data-slot="agent-row-definition-path"
									title="Where this agent is defined"
								>
									{a.definition_path}
								</p>
							{/if}

							{#if a.description !== null && a.description.length > 0}
								<p class="ag-row-desc" data-slot="agent-row-description">
									{a.description}
								</p>
							{/if}

							<div class="ag-row-footer">
								<span class="ag-row-created" data-slot="agent-row-created"
									>created <b>{formatRelative(a.created_at)}</b></span
								>
								<span class="ag-inspect"
									>Inspect agent <ArrowUpRight
										class="size-3 ag-inspect-arrow"
										aria-hidden="true"
									/></span
								>
							</div>
						</a>
					{/each}
				</div>
			{/if}
		{/if}
	</div>
</section>

