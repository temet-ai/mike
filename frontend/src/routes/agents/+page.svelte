<script lang="ts">
	import { onMount } from 'svelte';
	import { resolve } from '$app/paths';
	import { listAgents, type AgentListItem, type AgentSource } from '$lib/api/agents';
	import { ApiError } from '$lib/api';
	import { formatRelative } from '$lib/time';
	import EmptyStateOnboarding from '$lib/components/shared/EmptyStateOnboarding.svelte';
	import LoadErrorBanner from '$lib/components/shared/LoadErrorBanner.svelte';
	import FilterScopeStatus from '$lib/components/shared/FilterScopeStatus.svelte';
	import FilteredEmptyState from '$lib/components/shared/FilteredEmptyState.svelte';
	import PageIntro from '$lib/components/shared/PageIntro.svelte';
	import Tooltip from '$lib/components/shared/Tooltip.svelte';
	import { BookOpen, Bot, Search, ArrowUpRight, X } from '@lucide/svelte';
	import { revealSections } from '$lib/actions/reveal';
	import { Button } from '$lib/components/ui/button';
	import { shellState } from '$lib/stores/shellState.svelte';
	import { onApiCacheUpdate } from '$lib/stores/cache/apiCache.svelte';

	type SourceFilter = AgentSource | 'all';
	const SOURCE_FILTERS: Array<{ value: SourceFilter; label: string }> = [
		{ value: 'all', label: 'All' },
		{ value: 'observed', label: 'observed' },
		{ value: 'file_backed', label: 'file-backed' },
		{ value: 'dynamic', label: 'dynamic' },
		{ value: 'builtin', label: 'builtin' }
	];

	const SOURCE_TOOLTIP: Record<AgentSource, string> = {
		observed: 'Auto-captured from request traffic; no on-disk definition confirmed.',
		file_backed: 'Operator confirmed this agent has a matching .md file.',
		dynamic: 'One-shot / dynamically generated by Claude.',
		builtin: 'Ships with the harness itself (e.g. the default catch-all agent).'
	};

	const SOURCE_SLUG: Record<AgentSource, string | undefined> = {
		observed: 'mode-observed',
		file_backed: 'mode-file-backed',
		dynamic: 'mode-dynamic',
		builtin: 'mode-builtin'
	};

	const SOURCE_BADGE: Record<AgentSource, string> = {
		observed: 'badge-warning',
		file_backed: 'badge-active',
		dynamic: 'badge-analyzed',
		builtin: 'badge-muted'
	};

	let agents = $state<AgentListItem[]>([]);
	let error = $state<string | null>(null);
	let loading = $state(true);
	let sourceFilter = $state<SourceFilter>('all');
	let searchQuery = $state('');
	const normalizedSearch = $derived(searchQuery.trim().toLowerCase());

	async function refresh(): Promise<void> {
		loading = true;
		error = null;
		try {
			agents = await listAgents();
		} catch (err) {
			agents = [];
			error = err instanceof ApiError ? err.message : String(err);
		} finally {
			loading = false;
		}
	}

	onMount(() => {
		void refresh();
		const unsub = onApiCacheUpdate(
			'/api/agents',
			() => {
				void refresh();
			},
			{ prefix: true }
		);
		return () => {
			unsub();
		};
	});

	function openHelp(): void {
		shellState.helpDrawerOpen = true;
	}

	const sourceCounts = $derived.by(() => {
		const counts: Record<SourceFilter, number> = {
			all: agents.length,
			observed: 0,
			file_backed: 0,
			dynamic: 0,
			builtin: 0
		};
		for (const a of agents) {
			counts[a.source] += 1;
		}
		return counts;
	});

	const visibleAgents = $derived.by(() => {
		const filtered = agents.filter((agent) => {
			if (sourceFilter !== 'all' && agent.source !== sourceFilter) return false;
			if (!normalizedSearch) return true;
			return [
				agent.name,
				agent.description,
				agent.definition_path,
				...(agent.aliases ?? []).map((alias) => alias.alias)
			].some((value) => value?.toLowerCase().includes(normalizedSearch));
		});
		return [...filtered].sort((a, b) => {
			if (a.last_dispatched_at === null && b.last_dispatched_at === null) return 0;
			if (a.last_dispatched_at === null) return 1;
			if (b.last_dispatched_at === null) return -1;
			return Date.parse(b.last_dispatched_at) - Date.parse(a.last_dispatched_at);
		});
	});

	const scopeLabel = $derived.by((): string => {
		const parts: string[] = [];
		if (sourceFilter !== 'all') {
			const label = SOURCE_FILTERS.find((f) => f.value === sourceFilter)?.label ?? sourceFilter;
			parts.push(`source "${label}"`);
		}
		if (normalizedSearch) parts.push(`search "${searchQuery.trim()}"`);
		return parts.length > 0 ? parts.join(', ') : 'every registered agent';
	});
</script>

<svelte:head>
	<title>Agents — mike</title>
