#[test]
fn human_prompt_strips_task_notification_tags() {
    let body = json!({
        "messages": [{
            "role": "user",
            "content": "<task-notification>\n<task-id>abc123</task-id>\n<status>completed</status>\n<summary>Agent done</summary>\n</task-notification>\nWhat is the status?"
        }]
    });
    let result = extract_human_prompt(&body);
    assert_eq!(result, "What is the status?");
    assert!(!result.contains("task-notification"));
    assert!(!result.contains("abc123"));
}

#[test]
fn human_prompt_task_notification_only_uses_summary_fallback() {
    let content = "<task-notification>\n<task-id>bwhsef9la</task-id>\n<tool-use-id>toolu_01JoX95UiFShkqNUPh6mQvii</tool-use-id>\n<status>completed</status>\n<summary>Background command \"Run Wave 1 make check gate in background\" completed (exit code 0)</summary>\n</task-notification>";
    let body = json!({"messages": [{"role": "user", "content": content}]});
    let result = extract_human_prompt(&body);
    assert_eq!(
        result,
        "Task notification: Background command \"Run Wave 1 make check gate in background\" completed (exit code 0)"
    );
    assert!(!result.contains("task-notification"));
    assert!(!result.contains("bwhsef9la"));
}

