#!/usr/bin/env python3
"""docs-agent: update documentation when code lands on main.

Run as:  python scripts/docs-agent
"""

import os
import sys
from pathlib import Path

# Allow sibling modules (client, git_util) to be imported from the step files.
_HERE = Path(__file__).parent
sys.path.insert(0, str(_HERE))

import git_util
from steps import analyze, architecture, schema, guides, ui_help


def main() -> None:
    if not os.environ.get("OPENROUTER_API_KEY"):
        print("OPENROUTER_API_KEY not set — aborting")
        sys.exit(1)

    diff = git_util.diff_full()
    if not diff.strip():
        print("No diff between HEAD~1 and HEAD — nothing to do")
        return

    # ── Step 0: classify what changed ──────────────────────────────────────
    print("Analyzing changes...")
    changes = analyze.run()
    print(f"Summary : {changes['summary']}")
    print(
        f"Affects : architecture={changes['architecture']}  "
        f"schema={changes['schema']}  "
        f"guides={changes['guides']}  "
        f"ui_help={changes['ui_help']}"
    )

    if not any(changes[k] for k in ("architecture", "schema", "guides", "ui_help")):
        print("No documentation categories affected — done")
        return

    # ── Steps 1–4: run only what's needed ──────────────────────────────────
    updated_files: list[str] = []

    if changes["architecture"]:
        print("\nStep 1: architecture docs")
        updated_files.extend(architecture.run(diff))

    if changes["schema"]:
        print("\nStep 2: schema docs")
        updated_files.extend(schema.run(diff))

    if changes["guides"]:
        print("\nStep 3: developer guides")
        updated_files.extend(guides.run(diff))

    if changes["ui_help"]:
        print("\nStep 4: UI route docs")
        updated_files.extend(ui_help.run(diff))

    if not updated_files:
        print("\nAll steps returned NO_CHANGES — nothing to commit")
        return

    print(f"\nUpdated: {updated_files}")

    # ── Commit + PR ─────────────────────────────────────────────────────────
    commit_sha = os.environ.get("COMMIT_SHA", "unknown")[:8]
    branch = f"docs/agent-{commit_sha}"
    summary = changes["summary"]

    commit_msg = (
        f"docs: {summary} [docs-agent]\n\n"
        f"Triggered by {commit_sha}.\n"
        f"Files: {', '.join(updated_files)}"
    )

    pushed = git_util.commit_and_push(branch, commit_msg)
    if not pushed:
        print("Working tree clean after writes — unexpected, aborting PR creation")
        sys.exit(1)

    file_list = "\n".join(f"- `{f}`" for f in updated_files)
    pr_body = f"""\
Automated documentation update triggered by commit `{commit_sha}`.

**What changed:** {summary}

**Updated files:**
{file_list}

---
*Generated by docs-agent. Review for accuracy before merging.*"""

    # [docs-agent] in the title is load-bearing: on a squash-merge GitHub uses
    # the PR title as the commit message, so the push-trigger's
    # head_commit.message check catches it and skips re-running the workflow.
    git_util.create_pr(title=f"docs: {summary} [docs-agent]", body=pr_body)
    print("PR created.")


if __name__ == "__main__":
    main()
